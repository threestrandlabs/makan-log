#!/usr/bin/env node
// Generates src/theme/tokens.generated.ts from ROOT/design/tokens-v0.1.json.
// Token names are kept identical to the source so the design file stays the single source of truth.
const fs = require("fs");
const path = require("path");

const ROOT = path.resolve(__dirname, "../../..");
const TOKENS_JSON = path.join(ROOT, "design", "tokens-v0.1.json");
const OUT_FILE = path.resolve(__dirname, "../src/theme/tokens.generated.ts");

function main() {
  const tokens = JSON.parse(fs.readFileSync(TOKENS_JSON, "utf8"));

  const banner = `// GENERATED by scripts/build-theme.js from design/tokens-v0.1.json. Do not edit by hand.\n`;
  const body = `${banner}\nconst tokens = ${JSON.stringify(tokens, null, 2)} as const;\n\nexport default tokens;\n`;

  fs.mkdirSync(path.dirname(OUT_FILE), { recursive: true });
  fs.writeFileSync(OUT_FILE, body);
  console.log(`Wrote ${path.relative(process.cwd(), OUT_FILE)}`);
}

main();
